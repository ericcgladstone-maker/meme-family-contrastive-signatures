"""Generate main Figures 1-3 as 300-dpi COLOR PNGs (Okabe-Ito, CVD-safe).
Figure 4 is generated by make_all_figures.py (4-panel). Run from build/."""
import numpy as np, pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch, FancyArrowPatch

plt.rcParams.update({"font.family": "serif", "font.size": 9, "axes.spines.top": False,
                     "axes.spines.right": False, "axes.grid": True, "grid.color": "0.9",
                     "grid.linewidth": 0.6, "axes.edgecolor": "0.3", "savefig.dpi": 300,
                     "savefig.bbox": "tight"})
FIG = "../SSCR Submission/03_Figures/"
# Okabe-Ito colorblind-safe palette
C_CON = "#0072B2"   # contrastive / primary (blue)
C_BASE = "#E69F00"  # baseline / whole-image (orange)
C_NEG = "#D55E00"   # negative / observed reference (vermillion)
C_ACC = "#009E73"   # accent (green)
C_NULL = "#9AA7B0"  # muted gray for null / near-zero

t = pd.read_csv("first_results/ph4_manuscript_natcomms/natcomms_revision_v2/analysis_to_run/m2m4_results.csv")
s7 = pd.read_csv("../SSCR Submission/04_Tables/TableS7_family_recovery_matrix.csv")

# ---------- Figure 1: framework schematic ----------
fig, ax = plt.subplots(figsize=(7.2, 2.6)); ax.axis("off"); ax.set_xlim(0, 10); ax.set_ylim(0, 3)
boxes = [(0.6, "Documented\nmeme family\n(members)"), (2.4, "CLIP\nwhole-image\nembedding"),
         (4.2, "Sparse\ndecomposition\n(MSAE)"), (6.0, "Contrastive\nsignature\n(top-15 features)"),
         (7.9, "Raw signature\nresemblance +\nspecificity")]
for x, lab in boxes:
    ax.add_patch(FancyBboxPatch((x, 1.1), 1.4, 0.9, boxstyle="round,pad=0.06",
                 fc="#EAF3F9", ec=C_CON, lw=1.2))
    ax.text(x + 0.7, 1.55, lab, ha="center", va="center", fontsize=7.5)
for x in [2.05, 3.85, 5.65, 7.55]:
    ax.add_patch(FancyArrowPatch((x, 1.55), (x + 0.35, 1.55), arrowstyle="-|>", mutation_scale=10, color=C_CON))
ax.text(5, 0.35, "Leave-one-variant-out recovery vs. baselines   |   Reddit application: engagement",
        ha="center", fontsize=7.5, style="italic", color=C_ACC)
fig.savefig(FIG + "Figure1_framework.png"); fig.savefig(FIG + "Figure1_framework.svg"); plt.close(fig)

# ---------- Figure 2: family recovery ----------
fig, axs = plt.subplots(1, 3, figsize=(7.6, 2.9))
a = axs[0]
for _, r in s7.iterrows():
    a.plot([0, 1], [r["recur"], r["contrastive"]], color="0.7", lw=0.7, marker="o", ms=2.5, mfc=C_CON, mec=C_CON)
a.plot([0, 1], [s7["recur"].mean(), s7["contrastive"].mean()], color=C_NEG, lw=2.2, marker="s", ms=5)
a.set_xticks([0, 1]); a.set_xticklabels(["Recurrence", "Contrastive"]); a.set_ylabel("Recovery AUROC")
a.set_title("(a) Paired recovery", fontsize=9); a.set_xlim(-0.3, 1.3)
b = axs[1]
methods = [("recur", "Recur."), ("clip", "Whole-img"), ("surf_oracle", "Surface"),
           ("sae_cent", "Sp.cent."), ("sae_knn", "Sp.kNN"), ("contrastive", "Contrast"), ("logistic", "Classif.")]
for i, (col, lab) in enumerate(methods):
    y = s7[col].values; x = np.full_like(y, i) + np.random.default_rng(i).normal(0, 0.05, len(y))
    col_pt = C_CON if col == "contrastive" else C_NULL
    b.scatter(x, y, s=7, color=col_pt, alpha=0.8)
    b.plot([i - 0.25, i + 0.25], [y.mean()]*2, color=C_NEG, lw=2)
b.set_xticks(range(len(methods))); b.set_xticklabels([m[1] for m in methods], rotation=45, ha="right", fontsize=7)
b.set_ylabel("Recovery AUROC"); b.set_title("(b) By method", fontsize=9)
c = axs[2]
diff = (s7["contrastive"] - s7["sae_cent"]).sort_values().values
c.bar(range(len(diff)), diff, color=np.where(diff > 0, C_CON, C_NEG), width=0.9)
c.axhline(0, color="black", lw=0.8); c.set_xlabel("Family (sorted)"); c.set_ylabel("Contrastive − sparse centroid")
c.set_title("(c) Per-family gain", fontsize=9)
fig.tight_layout(); fig.savefig(FIG + "Figure2_recovery.png"); fig.savefig(FIG + "Figure2_recovery.svg"); plt.close(fig)

# ---------- Figure 3: adversarial decoys ----------
fig, ax = plt.subplots(figsize=(4.6, 3.0))
groups = ["Encoder-selected\ndecoys", "pHash-selected\ndecoys"]
con = [s7["adv_con"].mean(), t["adv_con_phash"].mean()]
clip = [s7["adv_clip"].mean(), t["adv_clip_phash"].mean()]
x = np.arange(2); w = 0.35
ax.bar(x - w/2, con, w, color=C_CON, label="Contrastive signature")
ax.bar(x + w/2, clip, w, color=C_BASE, label="Whole-image similarity")
for xi, (cc, cl) in enumerate(zip(con, clip)):
    ax.text(xi - w/2, cc + 0.01, f"{cc:.2f}", ha="center", fontsize=7)
    ax.text(xi + w/2, cl + 0.01, f"{cl:.2f}", ha="center", fontsize=7)
ax.axhline(0.5, color="0.5", ls=":", lw=0.8); ax.set_xticks(x); ax.set_xticklabels(groups)
ax.set_ylabel("Discrimination AUROC"); ax.set_ylim(0.4, 1.0); ax.legend(fontsize=7.5, frameon=False)
ax.set_title("Adversarial discrimination by decoy type", fontsize=9)
fig.tight_layout(); fig.savefig(FIG + "Figure3_adversarial.png"); fig.savefig(FIG + "Figure3_adversarial.svg"); plt.close(fig)

import os
for f in ["Figure1_framework", "Figure2_recovery", "Figure3_adversarial"]:
    print(f, os.path.getsize(FIG + f + ".png"), "bytes")
